#!/usr/bin/env bash
# =============================================================================
# WeberQ ERP — Docker Entrypoint
# Generates /etc/odoo/odoo.conf from environment variables at startup.
#
# Environment variables:
#   HOST        - PostgreSQL host        (default: db)
#   PORT        - PostgreSQL port        (default: 5432)
#   USER        - PostgreSQL user        (default: odoo)
#   PASSWORD    - PostgreSQL password    (required)
#   DB_NAME     - Odoo database name     (default: same as USER)
#   WORKERS     - Odoo worker processes  (default: 4)
#   MAX_CRON_THREADS - Cron workers     (default: 2)
#   LOG_LEVEL   - Odoo log level        (default: info)
#   ADMIN_PASSWD- Odoo master password  (default: random per start)
# =============================================================================

set -e

DB_HOST="${HOST:-db}"
DB_PORT="${PORT:-5432}"
DB_USER="${USER:-odoo}"
DB_PASSWORD="${PASSWORD:-}"
DB_NAME="${DB_NAME:-$DB_USER}"
WORKERS="${WORKERS:-4}"
MAX_CRON_THREADS="${MAX_CRON_THREADS:-2}"
LOG_LEVEL="${LOG_LEVEL:-info}"
ADMIN_PASSWD="${ADMIN_PASSWD:-}"

# The database manager is disabled below, but never fall back to a guessable
# master password
if [ -z "$ADMIN_PASSWD" ]; then
    echo "[entrypoint] WARNING: ADMIN_PASSWD not set, using a random master password"
    ADMIN_PASSWD="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
fi

# ─── Dynamically Build Addons Path ───────────────────────────────────────────
COMPILED_ADDONS_PATH="/opt/odoo/addons,/opt/odoo/custom_addons"
for dir in /opt/odoo/custom_addons/*/; do
    dir=${dir%/}
    if [ -d "$dir" ] && [ ! -f "$dir/__manifest__.py" ]; then
        COMPILED_ADDONS_PATH="${COMPILED_ADDONS_PATH},${dir}"
    fi
done

# ─── Generate odoo.conf ──────────────────────────────────────────────────────
cat > /etc/odoo/odoo.conf << EOF
[options]
; WeberQ ERP — auto-generated by docker-entrypoint.sh

; Addons paths
addons_path = ${COMPILED_ADDONS_PATH}

; Data directory (filestore, sessions)
data_dir = /var/lib/odoo

; Database
db_host = ${DB_HOST}
db_port = ${DB_PORT}
db_user = ${DB_USER}
db_password = ${DB_PASSWORD}

; Serve exactly one database and keep the public database manager
; (/web/database/manager: create, drop, backup, restore) switched off
db_name = ${DB_NAME}
dbfilter = ^${DB_NAME}$
list_db = False

; Master password (for DB management UI)
admin_passwd = ${ADMIN_PASSWD}

; Network (listen on all interfaces so Traefik can reach the container)
http_interface = 0.0.0.0
http_port = 8069
gevent_port = 8072
proxy_mode = True

; Workers (set 0 for dev single-thread mode)
workers = ${WORKERS}
max_cron_threads = ${MAX_CRON_THREADS}

; Logging (no logfile: logs go to stderr for docker logs)
log_level = ${LOG_LEVEL}
log_handler = :INFO

; Limits
limit_memory_hard = 2684354560
limit_memory_soft = 2147483648
limit_request = 8192
limit_time_cpu = 600
limit_time_real = 1200
EOF

echo "[entrypoint] odoo.conf written. Starting Odoo..."

exec python3 /opt/odoo/odoo-bin "$@"
